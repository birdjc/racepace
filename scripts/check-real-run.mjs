// Run the full recorded-run pipeline on a real GPX (path in argv[2]) and print a summary
import fs from 'fs';
import { buildCourse } from '../src/lib/course.js';
import { smoothElevation } from '../src/lib/profile.js';
import { buildWindows, hillSegments } from '../src/lib/segments.js';
import { getRaceWeather, getTimezone } from '../src/lib/weather.js';
import { attachWeather, computeAll, solveFlatSpeed } from '../src/lib/adjust.js';
import { analyseRecording, utcToLocal } from '../src/lib/recorded.js';
import { parseGpx } from '../src/lib/gpx.js';
const fmt = s => { s = Math.round(s); return `${Math.floor(s / 3600)}:${String(Math.floor(s % 3600 / 60)).padStart(2, '0')}:${String(s % 60).padStart(2, '0')}`; };
const pace = v => { const s = 1609.344 / v; return `${Math.floor(s / 60)}:${String(Math.round(s % 60)).padStart(2, '0')}`; };
const text = fs.readFileSync(process.argv[2], 'utf8');
const ts = parseGpx(text).timestamps;
const course = await buildCourse(text);
const prof = smoothElevation(course);
const base = buildWindows(course.points, prof.ele);
const hills = hillSegments(base);
const tz = await getTimezone(course.centroid.lat, course.centroid.lon);
const startLocal = utcToLocal(ts.startMs, tz);
const weather = await getRaceWeather({ lat: course.centroid.lat, lon: course.centroid.lon, startLocal, durationSec: ts.elapsedSec });
const t0 = course.points[0].t;
const W = attachWeather(base, w => (course.points[Math.round((w.i0 + w.i1) / 2)].t - t0) / 1000, weather.hours, startLocal);
const on = { grade: true, wind: true, heat: true };
const v0 = solveFlatSpeed(W, Math.round(ts.elapsedSec), on);
const res = computeAll(W, v0, on);
const rec = analyseRecording(W, course.points, on);
let gain = 0; W.forEach(w => { if (w.ele1 > w.ele0) gain += w.ele1 - w.ele0; });
console.log(`start ${startLocal} (${tz}) | ${(course.distance / 1609.344).toFixed(2)} mi | gain ${(gain * 3.28084).toFixed(0)} ft | ele from ${course.elevationSource}, SG ${prof.windowM} m | hills ${hills.length}`);
console.log(`weather: ${weather.source}; ${weather.hours.map(h => `${h.time.slice(11)} ${Math.round(h.tempC * 9 / 5 + 32)}F ${Math.round(h.rh)}% ${(h.windMs * 2.237).toFixed(0)}mph`).join(' | ')}`);
console.log(`elapsed ${fmt(ts.elapsedSec)} (${pace(course.distance / ts.elapsedSec)}/mi) -> flat equivalent ${fmt(course.distance / v0)} (${pace(v0)}/mi)`);
console.log(`impacts: grade ${res.impact.grade.toFixed(0)}s wind ${res.impact.wind.toFixed(0)}s heat ${res.impact.heat.toFixed(0)}s total ${res.impact.total.toFixed(0)}s`);
console.log(`stops: ${rec.stoppedCount} stretches, ${rec.stoppedSec.toFixed(0)} s | median effort ${pace(rec.medianFlat)}/mi | effort range ${pace(Math.max(...rec.flatSpeeds.filter(Number.isFinite)))}–${pace(Math.min(...rec.flatSpeeds.filter(Number.isFinite)))}/mi`);
